"""Generate docs/schemas.md from the Pydantic models in skillgraph.model (TASKS P1.2).

    python tools/gen_schema_docs.py           # rewrite docs/schemas.md
    python tools/gen_schema_docs.py --check   # exit 1 if docs/schemas.md is out of date

Field tables come from the models themselves, so they cannot drift; the narrative sections are fixed text below.
"""

from __future__ import annotations

import importlib
import sys
import types
import typing
from enum import Enum
from pathlib import Path

from pydantic import BaseModel

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "schemas.md"
MODULES = ["ids", "evidence", "source", "occupation", "conflict", "eligibility", "qualification"]
CONSTRAINTS = ("pattern", "min_length", "ge", "le", "multiple_of")

HEADER = """# Source-of-truth schemas

*Generated by `tools/gen_schema_docs.py` from `src/skillgraph/model/`; do not edit by hand (`--check` fails when stale).*
Normative sources: [ARCHITECTURE.md](../ARCHITECTURE.md) §9 and §10.1, [API_SPEC.md](../API_SPEC.md) §2.1–2.2.
Models are closed (`extra = forbid`) and their fields cannot be reassigned (containers inside them are still mutable); numbers are never coerced from strings or booleans.

## Guarantees

- **Provenance.** `Valued` refuses an `OFFICIAL`, `RULE_DERIVED` or `INFERENCE` value without `evidence_id`, and an
  `OFFICIAL` value without `value_status`. `Evidence` of class `OFFICIAL` requires `source_id`, `source_sha256` and a
  page or location; every other class refuses them. `RULE_DERIVED` / `INFERENCE` require `derived_from`.
- **Stored facts are OFFICIAL.** Qualification hours, NSQF level, minimum age, credits, NCO codes and NOS-membership
  values (including versions) are `OfficialValued`: `DECLARED`, `CONFIG`, `HYPOTHETICAL`, `INFERENCE` and
  `RULE_DERIVED` are refused. The general `Valued` accepts every class, for contexts that need them.
- **Classes stay distinct.** `DECLARED` needs `declared_field`, `CONFIG` needs `config_key`; neither may carry a source.
- **Credits are not hours.** `CreditValue` is the only credit type and must have `engine_use = NOT_USED`. Hours are
  `Valued[Hours]` and can never be `NOT_USED`. There is no field for incremental or reduced retraining hours: no
  source defines one (ARCHITECTURE §12).
- **Conflicts hold no chosen value.** `Conflict` has no selected/resolved field and only unresolved statuses. A value
  with `conflict_id` cannot have a safe `engine_use`.
- **Missing facts stay missing.** An unverified NCO title is `null` (`NOT_FOUND`/`NOT_CHECKED`); a source with no
  local file has `sha256 = null` even where the manifest records a hash for its error page.
- **Identifiers.** `<kind>:<official-key>`; slugs are derived by `slug_of`, resolved only through `SlugIndex`
  (which raises on a collision) and never parsed back into a code.

## Not validated here (by design)

Referential integrity (does an `evidence_id` / `qualification_id` exist), agreement between an `Evidence`
`source_sha256` and its `SourceDocument`, hour/credit sums and cross-source comparisons belong to the curated build
and the validation report (TASKS P1.4, P1.6). The schemas check format and local consistency only.
"""


def fmt(tp: object) -> str:
    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if tp is type(None):
        return "null"
    if origin is typing.Annotated:
        return fmt(args[0])
    if origin in (typing.Union, types.UnionType):
        return " | ".join(fmt(a) for a in args)
    if origin is typing.Literal:
        return "Literal[" + ", ".join(getattr(a, "value", a) if isinstance(a, Enum) else repr(a) for a in args) + "]"
    if origin is not None:
        return f"{getattr(origin, '__name__', origin)}[{', '.join(fmt(a) for a in args)}]"
    meta = getattr(tp, "__pydantic_generic_metadata__", None)
    if meta and meta["origin"] is not None:
        return f"{meta['origin'].__name__}[{', '.join(fmt(a) for a in meta['args'])}]"
    return getattr(tp, "__name__", str(tp))


def constraints(field: typing.Any) -> str:
    found = []
    for item in field.metadata:
        for name in CONSTRAINTS:
            if getattr(item, name, None) is not None:
                found.append(f"{name}={getattr(item, name)!r}")
    return ", ".join(found)


def render() -> str:
    out = [HEADER]
    for name in MODULES:
        mod = importlib.import_module(f"skillgraph.model.{name}")
        local = [o for o in vars(mod).values() if isinstance(o, type) and o.__module__ == mod.__name__ and "[" not in o.__name__]
        enums = [o for o in local if issubclass(o, Enum)]
        models = [o for o in local if issubclass(o, BaseModel)]
        out.append(f"\n## `{mod.__name__}`\n")
        for e in enums:
            out.append(f"**{e.__name__}** (enum): " + ", ".join(f"`{m.value}`" for m in e) + "\n")
        for m in models:
            out.append(f"\n### {m.__name__}\n")
            out.append("| Field | Type | Required | Constraints |\n|---|---|---|---|")
            for fname, f in m.model_fields.items():
                req = "yes" if f.is_required() else f"default `{f.default!r}`" if f.default_factory is None else "default"
                kind = fmt(f.annotation).replace("|", "\\|")  # a bare pipe would split the markdown table cell
                out.append(f"| `{fname}` | `{kind}` | {req} | {constraints(f).replace('|', chr(92) + '|')} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date; run python tools/gen_schema_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
